const video = JSON.parse(fs.readFileSync(VIDEO, "utf8"));
let n = 0;
const problems = [];
for (const scene of video.scenes) {
  for (const cut of scene.cuts) {
    const lines = [];
    for (const d of cut.dialogue ?? []) {
      const disp = T[d.id];
      if (!disp) {
        problems.push(`${d.id}: 組版未定義`);
        continue;
      }
      // 検証: 改行を除けば発話テキストと同一 / 各行17文字以内
      if (disp.replace(/\n/g, "") !== d.text.replace(/\n/g, "")) {
        problems.push(`${d.id}: displayText が発話テキストと不一致`);
      }
      for (const row of disp.split("\n")) {
        if ([...row].length > 17) problems.push(`${d.id}: 行が17文字超「${row}」`);
      }
      lines.push({ lineId: d.id, displayText: disp, emphasis: [], ruby: [] });
      n++;
    }
    if (lines.length > 0) cut.subtitle = { lines };
  }
}

if (problems.length) {
  console.error(problems.join("\n"));
  process.exit(1);
}
fs.writeFileSync(VIDEO, JSON.stringify(video, null, 2) + "\n", "utf8");
console.log(`typeset: ${n}行`);
